/**
 * Generate a complete SVG data URI from an icon definition and color
 */
export function getBrandIconDataUrl(
  icon: BrandIconDef,
  color?: string,
  bgEnabled = false,
  bgColor = '#FFFFFF'
): string {
  const chosenColor = color || icon.brandColor;
  const innerPaths = icon.renderSvg(chosenColor);
  const bg = bgEnabled ? `<rect width="100%" height="100%" rx="4" fill="${bgColor}"/>` : '';

  const svgStr = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${icon.viewBox}" width="128" height="128">${bg}${innerPaths}</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svgStr)}`;
}
